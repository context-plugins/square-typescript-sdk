import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { cardPaymentTimelineSchema, type CardPaymentTimeline } from "./card-payment-timeline.js";
import { cardSurchargeDetailsSchema, type CardSurchargeDetails } from "./card-surcharge-details.js";
import { cardSchema, type Card } from "./card.js";
import { deviceDetailsSchema, type DeviceDetails } from "./device-details.js";
import { errorSchema, type Error } from "./error.js";

/** Reflects the current status of a card payment. Contains only non-confidential information. */
export type CardPaymentDetails = {
  /** The card payment's current state. The state can be AUTHORIZED, CAPTURED, VOIDED, or FAILED. */
  status?: string;
  /**
   * Represents the payment details of a card to be used for payments. These details are determined
   * by the payment token generated by Web Payments SDK.
   */
  card?: Card;
  /**
   * The method used to enter the card's details for the payment. The method can be `KEYED`,
   * `SWIPED`, `EMV`, `ON_FILE`, or `CONTACTLESS`.
   */
  entryMethod?: string;
  /**
   * The status code returned from the Card Verification Value (CVV) check. The code can be
   * `CVV_ACCEPTED`, `CVV_REJECTED`, or `CVV_NOT_CHECKED`.
   */
  cvvStatus?: string;
  /**
   * The status code returned from the Address Verification System (AVS) check. The code can be
   * `AVS_ACCEPTED`, `AVS_REJECTED`, or `AVS_NOT_CHECKED`.
   */
  avsStatus?: string;
  /**
   * The status code returned by the card issuer that describes the payment's authorization status.
   */
  authResultCode?: string;
  /** For EMV payments, the application ID identifies the EMV application used for the payment. */
  applicationIdentifier?: string;
  /** For EMV payments, the human-readable name of the EMV application used for the payment. */
  applicationName?: string;
  /** For EMV payments, the cryptogram generated for the payment. */
  applicationCryptogram?: string;
  /**
   * For EMV payments, the method used to verify the cardholder's identity. The method can be `PIN`,
   * `SIGNATURE`, `PIN_AND_SIGNATURE`, `ON_DEVICE`, or `NONE`.
   */
  verificationMethod?: string;
  /**
   * For EMV payments, the results of the cardholder verification. The result can be `SUCCESS`,
   * `FAILURE`, or `UNKNOWN`.
   */
  verificationResults?: string;
  /**
   * The statement description sent to the card networks.
   *
   * Note: The actual statement description varies and is likely to be truncated and appended with
   * additional information on a per issuer basis.
   */
  statementDescription?: string;
  /** Details about the device that took the payment. */
  deviceDetails?: DeviceDetails;
  /** The timeline for card payments. */
  cardPaymentTimeline?: CardPaymentTimeline;
  /**
   * Whether the card must be physically present for the payment to be refunded. If set to `true`,
   * the card must be present.
   */
  refundRequiresCardPresence?: boolean;
  /** Information about errors encountered during the request. */
  errors?: Error[];
  /**
   * Details related to an attempt to apply a card surcharge to this payment. When surcharge
   * eligibility is not known in advance, such as when the card type (debit or credit) is required
   * to make the eligibility determination, proposed_card_surcharge_money and
   * proposed_additional_amount_money will match the values in the request, while
   * card_surcharge_money and additional_amount_money are present only when the payment has a
   * surcharge applied.
   */
  appliedCardSurchargeDetails?: CardSurchargeDetails;
  /**
   * The type of digital wallet used for this card payment, if applicable. Currently only populated
   * for in-person Apple Pay payments. Detection has no false positives but may have false negatives
   * (some Apple Pay payments may not be detected).
   *
   * For payments with `source_type` of `WALLET`, see `DigitalWalletDetails` instead.
   *
   * Values: `APPLE_PAY`
   */
  walletType?: string;
};

export const cardPaymentDetailsSchema: Schema<CardPaymentDetails> = s.object<CardPaymentDetails>({
  status: s.optional(s.string()),
  card: s.optional(s.lazy(() => cardSchema)),
  entryMethod: s.optional(s.string()),
  cvvStatus: s.optional(s.string()),
  avsStatus: s.optional(s.string()),
  authResultCode: s.optional(s.string()),
  applicationIdentifier: s.optional(s.string()),
  applicationName: s.optional(s.string()),
  applicationCryptogram: s.optional(s.string()),
  verificationMethod: s.optional(s.string()),
  verificationResults: s.optional(s.string()),
  statementDescription: s.optional(s.string()),
  deviceDetails: s.optional(s.lazy(() => deviceDetailsSchema)),
  cardPaymentTimeline: s.optional(s.lazy(() => cardPaymentTimelineSchema)),
  refundRequiresCardPresence: s.optional(s.boolean()),
  errors: s.optional(s.array(s.lazy(() => errorSchema))),
  appliedCardSurchargeDetails: s.optional(s.lazy(() => cardSurchargeDetailsSchema)),
  walletType: s.optional(s.string()),
  _keysMap: {
    entryMethod: "entry_method",
    cvvStatus: "cvv_status",
    avsStatus: "avs_status",
    authResultCode: "auth_result_code",
    applicationIdentifier: "application_identifier",
    applicationName: "application_name",
    applicationCryptogram: "application_cryptogram",
    verificationMethod: "verification_method",
    verificationResults: "verification_results",
    statementDescription: "statement_description",
    deviceDetails: "device_details",
    cardPaymentTimeline: "card_payment_timeline",
    refundRequiresCardPresence: "refund_requires_card_presence",
    appliedCardSurchargeDetails: "applied_card_surcharge_details",
    walletType: "wallet_type",
  },
});
