import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { addressSchema, type Address } from "./address.js";
import { cardBrandSchema, type CardBrand } from "./card-brand.js";
import { cardCoBrandSchema, type CardCoBrand } from "./card-co-brand.js";
import { cardIssuerAlertSchema, type CardIssuerAlert } from "./card-issuer-alert.js";
import { cardPrepaidTypeSchema, type CardPrepaidType } from "./card-prepaid-type.js";
import { cardTypeSchema, type CardType } from "./card-type.js";

/**
 * Represents the payment details of a card to be used for payments. These details are determined by
 * the payment token generated by Web Payments SDK.
 */
export type Card = {
  /** Unique ID for this card. Generated by Square. */
  id?: string;
  /** Indicates a card's brand, such as `VISA` or `MASTERCARD`. */
  cardBrand?: CardBrand;
  /** The last 4 digits of the card number. */
  last4?: string;
  /** The expiration month of the associated card as an integer between 1 and 12. */
  expMonth?: number | null;
  /** The four-digit year of the card's expiration date. */
  expYear?: number | null;
  /** The name of the cardholder. */
  cardholderName?: string | null;
  /**
   * Represents a postal address in a country. For more information, see [Working with
   * Addresses](https://developer.squareup.com/docs/build-basics/working-with-addresses).
   */
  billingAddress?: Address;
  /**
   * Intended as a Square-assigned identifier, based on the card number, to identify the card across
   * multiple locations within a single application.
   */
  fingerprint?: string;
  /** **Required** The ID of a [customer](entity:Customer) to be associated with the card. */
  customerId?: string | null;
  /** The ID of the merchant associated with the card. */
  merchantId?: string;
  /**
   * An optional user-defined reference ID that associates this card with another entity in an
   * external system. For example, a customer ID from an external customer management system.
   */
  referenceId?: string | null;
  /** Indicates whether or not a card can be used for payments. */
  enabled?: boolean;
  /** Indicates a card's type, such as `CREDIT` or `DEBIT`. */
  cardType?: CardType;
  /** Indicates a card's prepaid type, such as `NOT_PREPAID` or `PREPAID`. */
  prepaidType?: CardPrepaidType;
  /**
   * The first six digits of the card number, known as the Bank Identification Number (BIN). Only
   * the Payments API returns this field.
   */
  bin?: string;
  /**
   * Timestamp for when the card object was created on Square’s servers. In RFC 3339 format, e.g.,
   * "2016-09-04T23:59:33.123Z".
   */
  createdAt?: string;
  /**
   * Timestamp for when the card object was disabled on Square’s servers. In RFC 3339 format, e.g.,
   * "2016-09-04T23:59:33.123Z".
   */
  disabledAt?: string;
  /**
   * Current version number of the card. Increments with each card update. Requests to update an
   * existing Card object will be rejected unless the version in the request matches the current
   * version for the Card.
   */
  version?: number;
  /** Indicates the brand for a co-branded card. */
  cardCoBrand?: CardCoBrand;
  /** Indicates the type of issuer alert for a [card on file](entity:Card). */
  issuerAlert?: CardIssuerAlert;
  /**
   * The timestamp of when the current issuer alert was received and processed, in RFC 3339 format.
   *
   * This field is present only if there's an active issuer alert.
   */
  issuerAlertAt?: string;
  /**
   * Indicates whether the card is linked to a Health Savings Account (HSA) or Flexible Spending
   * Account (FSA), based on the card BIN.
   */
  hsaFsa?: boolean;
};

export const cardSchema: Schema<Card> = s.object<Card>({
  id: s.optional(s.string()),
  cardBrand: s.optional(s.lazy(() => cardBrandSchema)),
  last4: s.optional(s.string()),
  expMonth: s.optionalNullable(s.int()),
  expYear: s.optionalNullable(s.int()),
  cardholderName: s.optionalNullable(s.string()),
  billingAddress: s.optional(s.lazy(() => addressSchema)),
  fingerprint: s.optional(s.string()),
  customerId: s.optionalNullable(s.string()),
  merchantId: s.optional(s.string()),
  referenceId: s.optionalNullable(s.string()),
  enabled: s.optional(s.boolean()),
  cardType: s.optional(s.lazy(() => cardTypeSchema)),
  prepaidType: s.optional(s.lazy(() => cardPrepaidTypeSchema)),
  bin: s.optional(s.string()),
  createdAt: s.optional(s.string()),
  disabledAt: s.optional(s.string()),
  version: s.optional(s.int()),
  cardCoBrand: s.optional(s.lazy(() => cardCoBrandSchema)),
  issuerAlert: s.optional(s.lazy(() => cardIssuerAlertSchema)),
  issuerAlertAt: s.optional(s.string()),
  hsaFsa: s.optional(s.boolean()),
  _keysMap: {
    cardBrand: "card_brand",
    last4: "last_4",
    expMonth: "exp_month",
    expYear: "exp_year",
    cardholderName: "cardholder_name",
    billingAddress: "billing_address",
    customerId: "customer_id",
    merchantId: "merchant_id",
    referenceId: "reference_id",
    cardType: "card_type",
    prepaidType: "prepaid_type",
    createdAt: "created_at",
    disabledAt: "disabled_at",
    cardCoBrand: "card_co_brand",
    issuerAlert: "issuer_alert",
    issuerAlertAt: "issuer_alert_at",
    hsaFsa: "hsa_fsa",
  },
});
