import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { addressSchema, type Address } from "./address.js";
import { refundSchema, type Refund } from "./refund.js";
import { tenderSchema, type Tender } from "./tender.js";
import { transactionProductSchema, type TransactionProduct } from "./transaction-product.js";

/**
 * Represents a transaction processed with Square, either with the Connect API or with Square Point
 * of Sale.
 *
 * The `tenders` field of this object lists all methods of payment used to pay in the transaction.
 */
export type Transaction = {
  /** The transaction's unique ID, issued by Square payments servers. */
  id?: string;
  /** The ID of the transaction's associated location. */
  locationId?: string | null;
  /** The timestamp for when the transaction was created, in RFC 3339 format. */
  createdAt?: string;
  /** The tenders used to pay in the transaction. */
  tenders?: Tender[] | null;
  /** Refunds that have been applied to any tender in the transaction. */
  refunds?: Refund[] | null;
  /**
   * If the transaction was created with the [Charge](api-endpoint:Transactions-Charge) endpoint,
   * this value is the same as the value provided for the `reference_id` parameter in the request to
   * that endpoint. Otherwise, it is not set.
   */
  referenceId?: string | null;
  /** Indicates the Square product used to process a transaction. */
  product?: TransactionProduct;
  /**
   * If the transaction was created in the Square Point of Sale app, this value is the ID generated
   * for the transaction by Square Point of Sale.
   *
   * This ID has no relationship to the transaction's canonical `id`, which is generated by Square's
   * backend servers. This value is generated for bookkeeping purposes, in case the transaction
   * cannot immediately be completed (for example, if the transaction is processed in offline mode).
   *
   * It is not currently possible with the Connect API to perform a transaction lookup by this
   * value.
   */
  clientId?: string | null;
  /**
   * Represents a postal address in a country. For more information, see [Working with
   * Addresses](https://developer.squareup.com/docs/build-basics/working-with-addresses).
   */
  shippingAddress?: Address;
  /** The order_id is an identifier for the order associated with this transaction, if any. */
  orderId?: string | null;
};

export const transactionSchema: Schema<Transaction> = s.object<Transaction>({
  id: s.optional(s.string()),
  locationId: s.optionalNullable(s.string()),
  createdAt: s.optional(s.string()),
  tenders: s.optionalNullable(s.array(s.lazy(() => tenderSchema))),
  refunds: s.optionalNullable(s.array(s.lazy(() => refundSchema))),
  referenceId: s.optionalNullable(s.string()),
  product: s.optional(s.lazy(() => transactionProductSchema)),
  clientId: s.optionalNullable(s.string()),
  shippingAddress: s.optional(s.lazy(() => addressSchema)),
  orderId: s.optionalNullable(s.string()),
  _keysMap: {
    locationId: "location_id",
    createdAt: "created_at",
    referenceId: "reference_id",
    clientId: "client_id",
    shippingAddress: "shipping_address",
    orderId: "order_id",
  },
});
