import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import {
  inventoryAdjustmentGroupSchema,
  type InventoryAdjustmentGroup,
} from "./inventory-adjustment-group.js";
import {
  inventoryAdjustmentReasonIdSchema,
  type InventoryAdjustmentReasonId,
} from "./inventory-adjustment-reason-id.js";
import { inventoryStateSchema, type InventoryState } from "./inventory-state.js";
import { moneySchema, type Money } from "./money.js";
import { sourceApplicationSchema, type SourceApplication } from "./source-application.js";

/**
 * Represents a change in state or quantity of product inventory at a particular time and location.
 */
export type InventoryAdjustment = {
  /** A unique ID generated by Square for the `InventoryAdjustment`. */
  id?: string;
  /**
   * An optional ID provided by the application to tie the `InventoryAdjustment` to an external
   * system.
   */
  referenceId?: string | null;
  /** Indicates the state of a tracked item quantity in the lifecycle of goods. */
  fromState?: InventoryState;
  /** Indicates the state of a tracked item quantity in the lifecycle of goods. */
  toState?: InventoryState;
  /**
   * The Square-generated ID of the [Location](entity:Location) where the related quantity of items
   * is being tracked before the adjustment.
   */
  fromLocationId?: string | null;
  /**
   * The Square-generated ID of the [Location](entity:Location) where the related quantity of items
   * is being tracked after the adjustment.
   */
  toLocationId?: string | null;
  /** The Square-generated ID of the [CatalogObject](entity:CatalogObject) being tracked. */
  catalogObjectId?: string | null;
  /**
   * The [type](entity:CatalogObjectType) of the [CatalogObject](entity:CatalogObject) being
   * tracked.
   *
   * The Inventory API supports setting and reading the `"catalog_object_type": "ITEM_VARIATION"`
   * field value. In addition, it can also read the `"catalog_object_type": "ITEM"` field value that
   * is set by the Square Restaurants app.
   */
  catalogObjectType?: string | null;
  /**
   * The number of items affected by the adjustment as a decimal string. Can support up to 5 digits
   * after the decimal point.
   */
  quantity?: string | null;
  /**
   * Represents an amount of money. `Money` fields can be signed or unsigned. Fields that do not
   * explicitly define whether they are signed or unsigned are considered unsigned and can only hold
   * positive amounts. For signed fields, the sign of the value indicates the purpose of the money
   * transfer. See [Working with Monetary
   * Amounts](https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts) for
   * more information.
   */
  totalPriceMoney?: Money;
  /**
   * A client-generated RFC 3339-formatted timestamp that indicates when the inventory adjustment
   * took place. For inventory adjustment updates, the `occurred_at` timestamp cannot be older than
   * 24 hours or in the future relative to the time of the request.
   */
  occurredAt?: string | null;
  /** An RFC 3339-formatted timestamp that indicates when the inventory adjustment is received. */
  createdAt?: string;
  /** Represents information about the application used to generate a change. */
  source?: SourceApplication;
  /**
   * The Square-generated ID of the [Employee](entity:Employee) responsible for the inventory
   * adjustment.
   */
  employeeId?: string | null;
  /**
   * The Square-generated ID of the [Team Member](entity:TeamMember) responsible for the inventory
   * adjustment.
   */
  teamMemberId?: string | null;
  /**
   * The Square-generated ID of the [Transaction](entity:Transaction) that caused the adjustment.
   * Only relevant for payment-related state transitions.
   */
  transactionId?: string;
  /**
   * The Square-generated ID of the [Refund](entity:Refund) that caused the adjustment. Only
   * relevant for refund-related state transitions.
   */
  refundId?: string;
  /**
   * The Square-generated ID of the purchase order that caused the adjustment. Only relevant for
   * state transitions from the Square for Retail app.
   */
  purchaseOrderId?: string;
  /**
   * The Square-generated ID of the goods receipt that caused the adjustment. Only relevant for
   * state transitions from the Square for Retail app.
   */
  goodsReceiptId?: string;
  adjustmentGroup?: InventoryAdjustmentGroup;
  /**
   * Represents an amount of money. `Money` fields can be signed or unsigned. Fields that do not
   * explicitly define whether they are signed or unsigned are considered unsigned and can only hold
   * positive amounts. For signed fields, the sign of the value indicates the purpose of the money
   * transfer. See [Working with Monetary
   * Amounts](https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts) for
   * more information.
   */
  costMoney?: Money;
  /**
   * The Square-generated ID of the Vendor from which the merchant purchased this product. This
   * field is only applicable for stock receive adjustments that introduce stock into the system
   * (from_state is NONE or UNLINKED_RETURN). This field will only accept writes if the merchant has
   * an active subscription for either Retail Plus, Restaurants Plus, or Restaurants Premium.
   */
  vendorId?: string | null;
  /**
   * The Square-generated ID of the InventoryPhysicalCount (recount) that generated this adjustment,
   * if applicable. The quantity of an adjustment generated by a physical count cannot be edited.
   */
  physicalCountId?: string;
  /** Identifies a standard or custom inventory adjustment reason. */
  reasonId?: InventoryAdjustmentReasonId;
};

export const inventoryAdjustmentSchema: Schema<InventoryAdjustment> = s.object<InventoryAdjustment>({
  id: s.optional(s.string()),
  referenceId: s.optionalNullable(s.string()),
  fromState: s.optional(s.lazy(() => inventoryStateSchema)),
  toState: s.optional(s.lazy(() => inventoryStateSchema)),
  fromLocationId: s.optionalNullable(s.string()),
  toLocationId: s.optionalNullable(s.string()),
  catalogObjectId: s.optionalNullable(s.string()),
  catalogObjectType: s.optionalNullable(s.string()),
  quantity: s.optionalNullable(s.string()),
  totalPriceMoney: s.optional(s.lazy(() => moneySchema)),
  occurredAt: s.optionalNullable(s.string()),
  createdAt: s.optional(s.string()),
  source: s.optional(s.lazy(() => sourceApplicationSchema)),
  employeeId: s.optionalNullable(s.string()),
  teamMemberId: s.optionalNullable(s.string()),
  transactionId: s.optional(s.string()),
  refundId: s.optional(s.string()),
  purchaseOrderId: s.optional(s.string()),
  goodsReceiptId: s.optional(s.string()),
  adjustmentGroup: s.optional(s.lazy(() => inventoryAdjustmentGroupSchema)),
  costMoney: s.optional(s.lazy(() => moneySchema)),
  vendorId: s.optionalNullable(s.string()),
  physicalCountId: s.optional(s.string()),
  reasonId: s.optional(s.lazy(() => inventoryAdjustmentReasonIdSchema)),
  _keysMap: {
    referenceId: "reference_id",
    fromState: "from_state",
    toState: "to_state",
    fromLocationId: "from_location_id",
    toLocationId: "to_location_id",
    catalogObjectId: "catalog_object_id",
    catalogObjectType: "catalog_object_type",
    totalPriceMoney: "total_price_money",
    occurredAt: "occurred_at",
    createdAt: "created_at",
    employeeId: "employee_id",
    teamMemberId: "team_member_id",
    transactionId: "transaction_id",
    refundId: "refund_id",
    purchaseOrderId: "purchase_order_id",
    goodsReceiptId: "goods_receipt_id",
    adjustmentGroup: "adjustment_group",
    costMoney: "cost_money",
    vendorId: "vendor_id",
    physicalCountId: "physical_count_id",
    reasonId: "reason_id",
  },
});
