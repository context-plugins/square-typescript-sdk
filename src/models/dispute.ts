import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { cardBrandSchema, type CardBrand } from "./card-brand.js";
import { disputeReasonSchema, type DisputeReason } from "./dispute-reason.js";
import { disputeStateSchema, type DisputeState } from "./dispute-state.js";
import { disputedPaymentSchema, type DisputedPayment } from "./disputed-payment.js";
import { moneySchema, type Money } from "./money.js";

/**
 * Represents a [dispute](https://developer.squareup.com/docs/disputes-api/overview) a cardholder
 * initiated with their bank.
 */
export type Dispute = {
  /** The unique ID for this `Dispute`, generated by Square. */
  disputeId?: string | null;
  /** The unique ID for this `Dispute`, generated by Square. */
  id?: string;
  /**
   * Represents an amount of money. `Money` fields can be signed or unsigned. Fields that do not
   * explicitly define whether they are signed or unsigned are considered unsigned and can only hold
   * positive amounts. For signed fields, the sign of the value indicates the purpose of the money
   * transfer. See [Working with Monetary
   * Amounts](https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts) for
   * more information.
   */
  amountMoney?: Money;
  /** The list of possible reasons why a cardholder might initiate a dispute with their bank. */
  reason?: DisputeReason;
  /** The list of possible dispute states. */
  state?: DisputeState;
  /**
   * The deadline by which the seller must respond to the dispute, in [RFC 3339
   * format](https://developer.squareup.com/docs/build-basics/common-data-types/working-with-dates).
   */
  dueAt?: string | null;
  /** The payment the cardholder disputed. */
  disputedPayment?: DisputedPayment;
  /** The IDs of the evidence associated with the dispute. */
  evidenceIds?: string[] | null;
  /** Indicates a card's brand, such as `VISA` or `MASTERCARD`. */
  cardBrand?: CardBrand;
  /** The timestamp when the dispute was created, in RFC 3339 format. */
  createdAt?: string;
  /** The timestamp when the dispute was last updated, in RFC 3339 format. */
  updatedAt?: string;
  /** The ID of the dispute in the card brand system, generated by the card brand. */
  brandDisputeId?: string | null;
  /** The timestamp when the dispute was reported, in RFC 3339 format. */
  reportedDate?: string | null;
  /** The timestamp when the dispute was reported, in RFC 3339 format. */
  reportedAt?: string | null;
  /** The current version of the `Dispute`. */
  version?: number;
  /** The ID of the location where the dispute originated. */
  locationId?: string | null;
};

export const disputeSchema: Schema<Dispute> = s.object<Dispute>({
  disputeId: s.optionalNullable(s.string()),
  id: s.optional(s.string()),
  amountMoney: s.optional(s.lazy(() => moneySchema)),
  reason: s.optional(s.lazy(() => disputeReasonSchema)),
  state: s.optional(s.lazy(() => disputeStateSchema)),
  dueAt: s.optionalNullable(s.string()),
  disputedPayment: s.optional(s.lazy(() => disputedPaymentSchema)),
  evidenceIds: s.optionalNullable(s.array(s.string())),
  cardBrand: s.optional(s.lazy(() => cardBrandSchema)),
  createdAt: s.optional(s.string()),
  updatedAt: s.optional(s.string()),
  brandDisputeId: s.optionalNullable(s.string()),
  reportedDate: s.optionalNullable(s.string()),
  reportedAt: s.optionalNullable(s.string()),
  version: s.optional(s.int()),
  locationId: s.optionalNullable(s.string()),
  _keysMap: {
    disputeId: "dispute_id",
    amountMoney: "amount_money",
    dueAt: "due_at",
    disputedPayment: "disputed_payment",
    evidenceIds: "evidence_ids",
    cardBrand: "card_brand",
    createdAt: "created_at",
    updatedAt: "updated_at",
    brandDisputeId: "brand_dispute_id",
    reportedDate: "reported_date",
    reportedAt: "reported_at",
    locationId: "location_id",
  },
});
