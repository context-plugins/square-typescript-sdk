import * as s from "../core/validation/index.js";
import type { Schema } from "../core/validation/schema.js";
import { addressSchema, type Address } from "./address.js";
import { cashPaymentDetailsSchema, type CashPaymentDetails } from "./cash-payment-details.js";
import { customerDetailsSchema, type CustomerDetails } from "./customer-details.js";
import { externalPaymentDetailsSchema, type ExternalPaymentDetails } from "./external-payment-details.js";
import { moneySchema, type Money } from "./money.js";
import { offlinePaymentDetailsSchema, type OfflinePaymentDetails } from "./offline-payment-details.js";

/**
 * Describes a request to create a payment using
 * [CreatePayment](api-endpoint:Payments-CreatePayment).
 */
export type CreatePaymentRequest = {
  /**
   * The ID for the source of funds for this payment. This could be a payment token generated by the
   * Web Payments SDK for any of its [supported
   * methods](https://developer.squareup.com/docs/web-payments/overview#explore-payment-methods),
   * including cards, bank transfers, Afterpay or Cash App Pay. If recording a payment that the
   * seller received outside of Square, specify either "CASH" or "EXTERNAL". For more information,
   * see [Take Payments](https://developer.squareup.com/docs/payments-api/take-payments).
   */
  sourceId: string;
  /**
   * A unique string that identifies this `CreatePayment` request. Keys can be any valid string but
   * must be unique for every `CreatePayment` request.
   *
   * Note: The number of allowed characters might be less than the stated maximum, if multi-byte
   * characters are used.
   *
   * For more information, see
   * [Idempotency](https://developer.squareup.com/docs/working-with-apis/idempotency).
   */
  idempotencyKey: string;
  /**
   * Represents an amount of money. `Money` fields can be signed or unsigned. Fields that do not
   * explicitly define whether they are signed or unsigned are considered unsigned and can only hold
   * positive amounts. For signed fields, the sign of the value indicates the purpose of the money
   * transfer. See [Working with Monetary
   * Amounts](https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts) for
   * more information.
   */
  amountMoney?: Money;
  /**
   * Represents an amount of money. `Money` fields can be signed or unsigned. Fields that do not
   * explicitly define whether they are signed or unsigned are considered unsigned and can only hold
   * positive amounts. For signed fields, the sign of the value indicates the purpose of the money
   * transfer. See [Working with Monetary
   * Amounts](https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts) for
   * more information.
   */
  tipMoney?: Money;
  /**
   * Represents an amount of money. `Money` fields can be signed or unsigned. Fields that do not
   * explicitly define whether they are signed or unsigned are considered unsigned and can only hold
   * positive amounts. For signed fields, the sign of the value indicates the purpose of the money
   * transfer. See [Working with Monetary
   * Amounts](https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts) for
   * more information.
   */
  appFeeMoney?: Money;
  /**
   * The duration of time after the payment's creation when Square automatically either completes or
   * cancels the payment depending on the `delay_action` field value. For more information, see
   * [Time
   * threshold](https://developer.squareup.com/docs/payments-api/take-payments/card-payments/delayed-capture#time-threshold).
   *
   * This parameter should be specified as a time duration, in RFC 3339 format.
   *
   * Note: This feature is only supported for card payments. This parameter can only be set for a
   * delayed capture payment (`autocomplete=false`).
   *
   * Default:
   *
   * - Card-present payments: "PT36H" (36 hours) from the creation time.
   * - Card-not-present payments: "P7D" (7 days) from the creation time.
   */
  delayDuration?: string;
  /**
   * The action to be applied to the payment when the `delay_duration` has elapsed. The action must
   * be CANCEL or COMPLETE. For more information, see [Time
   * Threshold](https://developer.squareup.com/docs/payments-api/take-payments/card-payments/delayed-capture#time-threshold).
   *
   * Default: CANCEL
   */
  delayAction?: string;
  /**
   * If set to `true`, this payment will be completed when possible. If set to `false`, this payment
   * is held in an approved state until either explicitly completed (captured) or canceled (voided).
   * For more information, see [Delayed
   * capture](https://developer.squareup.com/docs/payments-api/take-payments/card-payments#delayed-capture-of-a-card-payment).
   *
   * Default: true
   */
  autocomplete?: boolean;
  /** Associates a previously created order with this payment. */
  orderId?: string;
  /**
   * The [Customer](entity:Customer) ID of the customer associated with the payment.
   *
   * This is required if the `source_id` refers to a card on file created using the Cards API.
   */
  customerId?: string;
  /**
   * The location ID to associate with the payment. If not specified, the [main
   * location](https://developer.squareup.com/docs/locations-api#about-the-main-location) is used.
   */
  locationId?: string;
  /** An optional [TeamMember](entity:TeamMember) ID to associate with this payment. */
  teamMemberId?: string;
  /**
   * A user-defined ID to associate with the payment.
   *
   * You can use this field to associate the payment to an entity in an external system (for
   * example, you might specify an order ID that is generated by a third-party shopping cart).
   */
  referenceId?: string;
  /**
   * An identifying token generated by
   * [payments.verifyBuyer()](https://developer.squareup.com/reference/sdks/web/payments/objects/Payments#Payments.verifyBuyer).
   * Verification tokens encapsulate customer device information and 3-D Secure challenge results to
   * indicate that Square has verified the buyer identity.
   *
   * For more information, see [SCA Overview](https://developer.squareup.com/docs/sca-overview).
   */
  verificationToken?: string;
  /**
   * If set to `true` and charging a Square Gift Card, a payment might be returned with
   * `amount_money` equal to less than what was requested. For example, a request for $20 when
   * charging a Square Gift Card with a balance of $5 results in an APPROVED payment of $5. You
   * might choose to prompt the buyer for an additional payment to cover the remainder or cancel the
   * Gift Card payment. This field cannot be `true` when `autocomplete = true`.
   *
   * For more information, see [Partial amount with Square Gift
   * Cards](https://developer.squareup.com/docs/payments-api/take-payments#partial-payment-gift-card).
   *
   * Default: false
   */
  acceptPartialAuthorization?: boolean;
  /** The buyer's email address. */
  buyerEmailAddress?: string;
  /**
   * The buyer's phone number. Must follow the following format:
   * 1. A leading + symbol (followed by a country code)
   * 2. The phone number can contain spaces and the special characters `(` , `)` , `-` , and `.`.
   *    Alphabetical characters aren't allowed.
   * 3. The phone number must contain between 9 and 16 digits.
   */
  buyerPhoneNumber?: string;
  /**
   * Represents a postal address in a country. For more information, see [Working with
   * Addresses](https://developer.squareup.com/docs/build-basics/working-with-addresses).
   */
  billingAddress?: Address;
  /**
   * Represents a postal address in a country. For more information, see [Working with
   * Addresses](https://developer.squareup.com/docs/build-basics/working-with-addresses).
   */
  shippingAddress?: Address;
  /** An optional note to be entered by the developer when creating a payment. */
  note?: string;
  /**
   * Optional additional payment information to include on the customer's card statement as part of
   * the statement description. This can be, for example, an invoice number, ticket number, or short
   * description that uniquely identifies the purchase.
   *
   * Note that the `statement_description_identifier` might get truncated on the statement
   * description to fit the required information including the Square identifier (SQ *) and name of
   * the seller taking the payment.
   */
  statementDescriptionIdentifier?: string;
  /**
   * Stores details about a cash payment. Contains only non-confidential information. For more
   * information, see [Take Cash
   * Payments](https://developer.squareup.com/docs/payments-api/take-payments/cash-payments).
   */
  cashDetails?: CashPaymentDetails;
  /**
   * Stores details about an external payment. Contains only non-confidential information. For more
   * information, see [Take External
   * Payments](https://developer.squareup.com/docs/payments-api/take-payments/external-payments).
   */
  externalDetails?: ExternalPaymentDetails;
  /** Details about the customer making the payment. */
  customerDetails?: CustomerDetails;
  /** Details specific to offline payments. */
  offlinePaymentDetails?: OfflinePaymentDetails;
};

export const createPaymentRequestSchema: Schema<CreatePaymentRequest> = s.object<CreatePaymentRequest>({
  sourceId: s.string(),
  idempotencyKey: s.string(),
  amountMoney: s.optional(s.lazy(() => moneySchema)),
  tipMoney: s.optional(s.lazy(() => moneySchema)),
  appFeeMoney: s.optional(s.lazy(() => moneySchema)),
  delayDuration: s.optional(s.string()),
  delayAction: s.optional(s.string()),
  autocomplete: s.optional(s.boolean()),
  orderId: s.optional(s.string()),
  customerId: s.optional(s.string()),
  locationId: s.optional(s.string()),
  teamMemberId: s.optional(s.string()),
  referenceId: s.optional(s.string()),
  verificationToken: s.optional(s.string()),
  acceptPartialAuthorization: s.optional(s.boolean()),
  buyerEmailAddress: s.optional(s.string()),
  buyerPhoneNumber: s.optional(s.string()),
  billingAddress: s.optional(s.lazy(() => addressSchema)),
  shippingAddress: s.optional(s.lazy(() => addressSchema)),
  note: s.optional(s.string()),
  statementDescriptionIdentifier: s.optional(s.string()),
  cashDetails: s.optional(s.lazy(() => cashPaymentDetailsSchema)),
  externalDetails: s.optional(s.lazy(() => externalPaymentDetailsSchema)),
  customerDetails: s.optional(s.lazy(() => customerDetailsSchema)),
  offlinePaymentDetails: s.optional(s.lazy(() => offlinePaymentDetailsSchema)),
  _keysMap: {
    sourceId: "source_id",
    idempotencyKey: "idempotency_key",
    amountMoney: "amount_money",
    tipMoney: "tip_money",
    appFeeMoney: "app_fee_money",
    delayDuration: "delay_duration",
    delayAction: "delay_action",
    orderId: "order_id",
    customerId: "customer_id",
    locationId: "location_id",
    teamMemberId: "team_member_id",
    referenceId: "reference_id",
    verificationToken: "verification_token",
    acceptPartialAuthorization: "accept_partial_authorization",
    buyerEmailAddress: "buyer_email_address",
    buyerPhoneNumber: "buyer_phone_number",
    billingAddress: "billing_address",
    shippingAddress: "shipping_address",
    statementDescriptionIdentifier: "statement_description_identifier",
    cashDetails: "cash_details",
    externalDetails: "external_details",
    customerDetails: "customer_details",
    offlinePaymentDetails: "offline_payment_details",
  },
});
